    for sp in [x for x in re.split('M', pm.group(1)) if x.strip()]:
        pts = [tuple(float(v) for v in p.split(',')) for p in re.sub(r'\s*L\s*', ' ', sp.strip()).split()]
        for (x0, y0), (x1, y1) in zip(pts, pts[1:]):
            X0, X1, Y0, Y1 = sv['x'] + x0 * sx, sv['x'] + x1 * sx, sv['y'] + y0 * sy, sv['y'] + y1 * sy
