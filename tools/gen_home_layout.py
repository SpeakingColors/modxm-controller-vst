#!/usr/bin/env python3
"""GENERATES src/HomeLayout.h from the extractor JSON of docs/mockups/MODX2_Home.dc.html.
usage: node tools/extract_mockup.js docs/mockups/MODX2_Home.dc.html home.json && python3 tools/gen_home_layout.py home.json src/HomeLayout.h
Controls are bound to parameter ids by their position (BIND below). Everything else is drawn exactly as in the mockup."""
import json, re, sys

d = json.load(open(sys.argv[1]))
out = open(sys.argv[2], 'w')

def col(c):
    if isinstance(c, str):
        c = c.strip()
        if c.startswith('#'):
            h = c[1:]
            if len(h) == 3: h = ''.join(x * 2 for x in h)
            return 0xFF000000 | int(h, 16)
        m = [float(v) for v in re.findall(r'[\d.]+', c)]
        a = m[3] if len(m) > 3 else 1.0
        return (round(a * 255) << 24) | (int(m[0]) << 16) | (int(m[1]) << 8) | int(m[2])
    a = c[3]
    return (round(a * 255) << 24) | (int(c[0]) << 16) | (int(c[1]) << 8) | int(c[2])

def cstr(s): return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'

# position (x, y rounded) -> parameter id; knobs and bars the plugin can drive from the MODX M Data List
BIND_KNOB = {
 (87, 56): ('s_06000232', 'Reverb Return'), (133, 56): ('s_06000238', 'Variation Return'), (179, 56): ('s_06000208', 'Performance Pan'),
 (453, 56): ('s_06000220', 'Portamento Time'),
 (91, 382): ('s_1p000238', 'Assignable Knob 1 Value'), (145, 382): ('s_1p00023a', 'Assignable Knob 2 Value'), (199, 382): ('s_1p00023c', 'Assignable Knob 3 Value'),
 (253, 382): ('s_1p00023e', 'Assignable Knob 4 Value'), (91, 438): ('s_1p000240', 'Assignable Knob 5 Value'), (145, 438): ('s_1p000242', 'Assignable Knob 6 Value'),
 (199, 438): ('s_1p000244', 'Assignable Knob 7 Value'),
 (298, 376): ('s_06000d00', 'Super Knob Value'),
 (513, 132): ('s_06000212', 'FEG Attack Time'), (559, 132): ('s_06000214', 'FEG Decay Time'), (605, 132): ('s_06000216', 'FEG Release Time'),
 (513, 182): ('s_0600021a', 'Cutoff Frequency'), (559, 182): ('s_0600021c', 'Resonance'), (609, 182): ('s_06000218', 'FEG Depth'),
 (710, 216): ('s_0600020a', 'AEG Attack Time'), (756, 216): ('s_0600020c', 'AEG Decay Time'), (802, 216): ('s_0600020e', 'AEG Sustain Level'), (848, 216): ('s_06000210', 'AEG Release Time'),
 (944, 222): ('s_06000232', 'Reverb Return'), (1006, 222): ('s_0600023c', 'Send Variation To Reverb'), (1068, 222): ('s_06000238', 'Variation Return'),
 (517, 545): ('s_06000238', 'Variation Return'), (517, 585): ('s_06000232', 'Reverb Return'),
}
BIND_BAR = {(219, 71): ('s_06000206', 'Performance Volume')}
# text start -> (param, on style, off style)
BIND_TOGGLE = {'Porta': ('s_06000100', 'Portamento Switch'), 'Arp Master': ('s_06000109', 'Arpeggio Master Switch'), 'MS Master': ('s_0600010a', 'Motion Seq Master Switch')}

def near(a, b): return abs(a - round(b)) <= 1

o = []
o.append('// GENERATED by tools/gen_home_layout.py from docs/mockups/MODX2_Home.dc.html (tools/extract_mockup.js). Do not edit by hand.\n')
o.append('#pragma once\n#include <cstdint>\nnamespace modx::home\n{\n')
o.append('constexpr int W = %d, H = %d, kCheek = 34;   // content space; the wood cheeks are drawn outside it\n' % (d['W'], d['H']))
o.append('struct Rect { float x, y, w, h; uint32_t bg; float bw[4]; uint32_t bc; float rad; };\n')
o.append('struct Text { float x, y, w, h; const char* s; float fs; int fw; uint32_t c; float ls; };\n')
o.append('struct Svg { float x, y, w, h; const char* svg; };\n')
o.append('struct Knob { float x, y, w, h; const char* label; const char* paramId; const char* tip; float frac; bool big; uint32_t track, body, arc, hub, needle; float r, sw; float vx, vy, vw, vh; uint32_t valCol; float valFs; const char* val; };\n')
o.append('struct Bar { float x, y, w, h; float frac; uint32_t bg, fill; float rad; const char* paramId; const char* tip; };\n')
o.append('struct Toggle { int rect, text; const char* paramId; const char* tip; uint32_t onBg, offBg, onTx, offTx; };\n')
o.append('struct Op { int kind, idx; };   // 0 rect, 1 text, 2 svg, 3 knob, 4 bar; drawn in this order\n\n')

o.append('inline constexpr Rect rects[] = {\n')
for r in d['rects']:
    o.append('  { %.1ff, %.1ff, %.1ff, %.1ff, 0x%08Xu, { %.1ff, %.1ff, %.1ff, %.1ff }, 0x%08Xu, %.1ff },\n' % (r['x'], r['y'], r['w'], r['h'], col(r['bg']), *r['bw'], col(r['bc']), r['rad'][0]))
o.append('};\n\n')
o.append('inline constexpr Text texts[] = {\n')
for t in d['texts']:
    s = t['s'].upper() if t['tt'] == 'uppercase' else t['s']
    o.append('  { %.1ff, %.1ff, %.1ff, %.1ff, %s, %.1ff, %d, 0x%08Xu, %.2ff },\n' % (t['x'], t['y'], t['w'], t['h'], cstr(s), t['fs'], t['fw'], col(t['c']), t['ls']))
o.append('};\n\n')
o.append('inline constexpr Svg svgs[] = {\n')
for s in d['svgs']:
    svg = re.sub(r'\s+xmlns="[^"]*"', '', s['svg'])
    svg = svg.replace('<svg', '<svg xmlns="http://www.w3.org/2000/svg"', 1)
    o.append('  { %.1ff, %.1ff, %.1ff, %.1ff, R"svg(%s)svg" },\n' % (s['x'], s['y'], s['w'], s['h'], svg))
o.append('};\n\n')
o.append('inline constexpr Knob knobs[] = {\n')
nb = 0
for k in d['knobs']:
    key = (round(k['x']), round(k['y']))
    b = next((v for kk, v in BIND_KNOB.items() if near(kk[0], k['x']) and near(kk[1], k['y'])), None)
    if b: nb += 1
    vr = k['valRect'] or {'x': 0, 'y': 0, 'w': 0, 'h': 0}
    tip = (k['label'] + ': ' + b[1]) if b else (k['label'] + ': not wired yet')
    o.append('  { %.1ff, %.1ff, %.1ff, %.1ff, %s, %s, %s, %.3ff, %s, 0x%08Xu, 0x%08Xu, 0x%08Xu, 0x%08Xu, 0x%08Xu, %.1ff, %.1ff, %.1ff, %.1ff, %.1ff, %.1ff, 0x%08Xu, %.1ff, %s },\n' % (
        k['x'], k['y'], k['w'], k['h'], cstr(k['label']), cstr(b[0]) if b else 'nullptr', cstr(tip), k['frac'], 'true' if k['big'] else 'false',
        col(k['track'] or '#33373E'), col(k['body'] or '#121417'), col(k['arcCol'] or '#2ECBD5'), col(k['hub'] or '#2A2D33'), col(k['needle'] or '#F0F1F3'), k['r'], k['sw'],
        vr['x'], vr['y'], vr['w'], vr['h'], col(k['valColor'] or 'rgb(142,148,157)'), 10.0, cstr(k['valText'])))
o.append('};\n\n')
o.append('inline constexpr Bar bars[] = {\n')
for b in d['bars']:
    bb = next((v for kk, v in BIND_BAR.items() if near(kk[0], b['x']) and near(kk[1], b['y'])), None)
    o.append('  { %.1ff, %.1ff, %.1ff, %.1ff, %.3ff, 0x%08Xu, 0x%08Xu, %.1ff, %s, %s },\n' % (b['x'], b['y'], b['w'], b['h'], b['frac'], col(b['bg']), col(b['fill']), b['rad'], cstr(bb[0]) if bb else 'nullptr', cstr(bb[1] if bb else 'not wired yet')))
o.append('};\n\n')

# toggles: find rect containing the text
def find_rect_text(start):
    t = next(i for i, t in enumerate(d['texts']) if t['s'].startswith(start))
    tx = d['texts'][t]; cx, cy = tx['x'] + tx['w'] / 2, tx['y'] + tx['h'] / 2
    best = None
    for i, r in enumerate(d['rects']):
        if r['x'] <= cx <= r['x'] + r['w'] and r['y'] <= cy <= r['y'] + r['h'] and r['w'] < 120 and r['h'] < 40:
            if best is None or r['w'] * r['h'] < d['rects'][best]['w'] * d['rects'][best]['h']: best = i
    return best, t
porta_r, porta_t = find_rect_text('Porta'); arp_r, arp_t = find_rect_text('Arp'); ms_r, ms_t = find_rect_text('MS')
off_bg = col(d['rects'][porta_r]['bg']); off_tx = col(d['texts'][porta_t]['c']); on_bg = col(d['rects'][arp_r]['bg']); on_tx = col(d['texts'][arp_t]['c'])
o.append('inline constexpr Toggle toggles[] = {\n')
for name, r_, t_ in (('Porta', porta_r, porta_t), ('Arp Master', arp_r, arp_t), ('MS Master', ms_r, ms_t)):
    p = BIND_TOGGLE[name]
    o.append('  { %d, %d, %s, %s, 0x%08Xu, 0x%08Xu, 0x%08Xu, 0x%08Xu },\n' % (r_, t_, cstr(p[0]), cstr(p[1]), on_bg, off_bg, on_tx, off_tx))
o.append('};\n\n')
# scene buttons: 8 rects around Scene1..8 texts
scene = []
for n in range(1, 9):
    r_, t_ = find_rect_text('Scene%d' % n); scene.append((r_, t_))
sel_bg = col(d['rects'][scene[0][0]]['bg']); un_bg = col(d['rects'][scene[1][0]]['bg']); sel_tx = col(d['texts'][scene[0][1]]['c']); un_tx = col(d['texts'][scene[1][1]]['c'])
o.append('inline constexpr int sceneRect[8] = { %s };\ninline constexpr int sceneText[8] = { %s };\n' % (', '.join(str(a) for a, b in scene), ', '.join(str(b) for a, b in scene)))
o.append('inline constexpr uint32_t sceneSelBg = 0x%08Xu, sceneOffBg = 0x%08Xu, sceneSelTx = 0x%08Xu, sceneOffTx = 0x%08Xu;\n\n' % (sel_bg, un_bg, sel_tx, un_tx))
# part table rows: 8 rows y positions from the "Mute" texts
rows = [t for t in d['texts'] if t['s'] == 'Mute']
o.append('inline constexpr float partRowY[] = { %s };   // top of each part row (Mute text y)\n' % ', '.join('%.1ff' % r['y'] for r in rows))
# footprint of the hit areas for header buttons
for key in ('⤡ 100%',):
    t = next(t for t in d['texts'] if key in t['s'])
    o.append('inline constexpr float reset100X = %.1ff, reset100Y = 11.0f, reset100W = 58.0f, reset100H = 24.0f;\n' % (t['x'] - 14))
o.append('\ninline constexpr Op ops[] = {\n')
kinds = {'rect': 0, 'text': 1, 'svg': 2, 'knob': 3, 'bar': 4}
o.append(',\n'.join('  { %d, %d }' % (kinds[k], i) for k, i in d['ops']))
o.append('\n};\n}\n')
out.write(''.join(o)); out.close()
print('knobs', len(d['knobs']), 'bound', nb, 'ops', len(d['ops']))
