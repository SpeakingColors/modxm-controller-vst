def col(c):
    if isinstance(c, str):
        c = c.strip()
        if c.startswith('#'):
            h = c[1:]
            if len(h) == 3: h = ''.join(x * 2 for x in h)
            return 0xFF000000 | int(h, 16)
        m = [float(v) for v in re.findall(r'[\d.]+', c)]
        a = m[3] if len(m) > 3 else 1.0
        return (round(a * 255) << 24) | (int(m[0]) << 16) | (int(m[1]) << 8) | int(m[2])
    a = c[3]
    return (round(a * 255) << 24) | (int(c[0]) << 16) | (int(c[1]) << 8) | int(c[2])

