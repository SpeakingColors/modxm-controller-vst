for si, sv in enumerate(d['svgs']):
    m = re.search(r'viewBox="[\d.\s-]+"', sv['svg']); 
    if 'preserveAspectRatio="none"' not in sv['svg'] or '<path' not in sv['svg'] or re.search(r'<(circle|rect|line|text)', sv['svg']): continue
